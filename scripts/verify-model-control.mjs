import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';

const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1000 } });
const errors = []; page.on('pageerror', error => errors.push(error.message));
await fs.mkdir('tmp/model-control', { recursive: true });
try {
    await page.goto(process.env.DIRECTOR_URL || 'http://127.0.0.1:5183');
    await page.waitForFunction(() => !!window.__director);
    const fixture = await page.evaluate(() => {
        const p = window.__director.getProject();
        const e = p.entities.find(e => e.kind === 'actor');
        e.clips = []; e.path = null; e.position = [0,0,0]; e.pose = {}; e.poseKeys = [];
        p.room.enabled = false; p.entities = p.entities.filter(item => item.id === e.id || item.kind === 'camera');
        for (const camera of p.entities.filter(item => item.camera)) { camera.camera.targetId = ''; camera.camera.mode = 'free'; }
        p.duration = .5; p.cuts = [p.cuts[0]];
        window.__director.replaceProject(p); window.__director.setTime(.25);
        return { actor: e.id, project: p };
    });
    await page.locator(`[data-select="${fixture.actor}"]`).first().click();
    await page.locator('#model-control-open').click();
    await page.locator('#model-control-start').waitFor({ state: 'visible' });
    await page.screenshot({ path: 'tmp/model-control/ready.png' });
    await page.locator('#model-control-start').click();
    await page.keyboard.down('w'); await page.waitForTimeout(450);
    await page.keyboard.down('Shift'); await page.waitForTimeout(450);
    await page.keyboard.up('Shift'); await page.keyboard.up('w');
    await page.keyboard.press('Space');
    const paused = await page.locator('#model-control-status').textContent();
    await page.waitForTimeout(350);
    assert.equal(await page.locator('#model-control-status').textContent(), paused, 'paused time must not advance');
    assert.match(paused, /已暂停/);
    const busyResult = await page.evaluate(async () => {
        const read = await window.__director.callTool('director_read', {});
        return window.__director.callTool('director_apply', { revision: read.data.revision, requestId: 'recording-busy-test', operations: [{ operation: 'project', patch: { name: 'must-not-write' } }] });
    });
    assert.equal(busyResult.ok, false, 'MCP cannot write over a live recording');
    await page.keyboard.press('Space'); await page.keyboard.down('d'); await page.waitForTimeout(250); await page.keyboard.up('d');
    await page.screenshot({ path: 'tmp/model-control/recording.png' });
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('#model-control').hidden);
    const recorded = await page.evaluate(() => window.__director.getProject());
    const actor = recorded.entities.find(e => e.id === fixture.actor);
    assert.ok(recorded.duration > .5, 'recording extends scene duration');
    assert.ok(actor.path.points.length >= 3);
    assert.ok(actor.clips.some(c => c.action === 'walk'));
    assert.ok(actor.clips.some(c => c.action === 'run'));
    assert.deepEqual(recorded.entities.filter(e => e.kind === 'camera'), fixture.project.entities.filter(e => e.kind === 'camera'));
    assert.deepEqual(recorded.cuts, fixture.project.cuts);
    await page.locator('[data-act="undo"]').click();
    assert.deepEqual(await page.evaluate(id => window.__director.getProject().entities.find(e => e.id === id), fixture.actor), fixture.project.entities.find(e => e.id === fixture.actor));
    await page.locator('[data-act="redo"]').click();
    assert.deepEqual(await page.evaluate(id => window.__director.getProject().entities.find(e => e.id === id), fixture.actor), actor);
    const downloadEvent = page.waitForEvent('download'); await page.locator('[data-act="save"]').click();
    const download = await downloadEvent; const file = path.resolve('tmp/model-control/recorded.director'); await download.saveAs(file);
    await page.locator('#project-file').setInputFiles(file);
    await page.waitForFunction(id => window.__director.getProject().entities.find(e => e.id === id)?.path?.points.length >= 3, fixture.actor);
    const signature = await page.evaluate(() => { window.__director.setTime(.5); return window.__director.signature(); });
    assert.deepEqual(await page.evaluate(() => { window.__director.setTime(0); window.__director.setTime(.8); window.__director.setTime(.5); return window.__director.signature(); }), signature);
    await page.locator(`[data-select="${fixture.actor}"]`).first().click();
    await page.locator('#model-control-open').click(); await page.locator('#model-control-start').click();
    await page.keyboard.press('Space');
    await page.evaluate(() => { window.__director.getEngine().orbit.enableDamping = false; });
    const stage = await page.locator('#stage-canvas canvas').boundingBox();
    await page.mouse.move(stage.x + stage.width / 2, stage.y + stage.height / 2);
    await page.mouse.down(); await page.mouse.move(stage.x + stage.width / 2 + 60, stage.y + stage.height / 2 + 15, { steps: 8 }); await page.mouse.up();
    await page.waitForTimeout(300);
    const orbitAfterRelease = await page.evaluate(() => window.__director.getEngine().editorCamera.position.toArray());
    await page.mouse.move(stage.x + stage.width / 2 - 70, stage.y + stage.height / 2 - 25, { steps: 5 });
    await page.waitForTimeout(300);
    const orbitAfterHover = await page.evaluate(() => window.__director.getEngine().editorCamera.position.toArray());
    assert.ok(Math.hypot(...orbitAfterHover.map((n, i) => n - orbitAfterRelease[i])) < .1, 'orbit drag ends on mouse release');
    await page.keyboard.press('Space');
    await page.keyboard.down('r'); await page.waitForTimeout(250); await page.keyboard.up('r');
    await page.keyboard.press('Escape');
    assert.deepEqual(await page.evaluate(id => window.__director.getProject().entities.find(e => e.id === id), fixture.actor), actor, 'cancel must discard the take');
    await page.setViewportSize({ width: 1000, height: 720 });
    await page.locator('#model-control-open').click();
    const bounds = await page.locator('#model-control').evaluate(el => ({ rect: el.getBoundingClientRect().toJSON(), overflow: el.scrollWidth > el.clientWidth }));
    assert.equal(bounds.overflow, false); assert.ok(bounds.rect.left >= 0 && bounds.rect.right <= 1000 && bounds.rect.top >= 0 && bounds.rect.bottom <= 720);
    await page.screenshot({ path: 'tmp/model-control/narrow.png' });
    assert.equal(await page.locator('#model-control-close').isVisible(), true);
    assert.deepEqual(errors, []);
    console.log(JSON.stringify({ ok: true, points: actor.path.points.length, duration: recorded.duration, actions: actor.clips.map(c => c.action), checks: ['keyboard', 'pause', 'extend duration', 'MCP busy', 'undo/redo', 'save/reopen', 'cancel', 'deterministic replay', 'narrow UI'] }));
} finally { await browser.close(); }
